#!/usr/bin/env python3
"""Resolve Ubuntu .deb packages to pinned (url, sha256) pairs.

Regenerates //bazel/deps:debs.bzl from the host's apt metadata. The generated
file is checked in, so ordinary builds never need apt -- only a maintainer
bumping the pinned dependency versions does.

Usage: python3 bazel/deps/resolve_debs.py
"""

import re
import subprocess
import sys
from pathlib import Path

# Packages are grouped per generated repository. Each group becomes one
# `deb_packages` repo whose file tree is the union of the extracted packages.
GROUPS = {
    "qt5": [
        # Headers, .prl files and the unversioned .so symlinks.
        "qtbase5-dev",
        # moc, uic, rcc.
        "qtbase5-dev-tools",
        # Shared libraries and the Qt platform plugins.
        "libqt5core5t64",
        "libqt5gui5t64",
        "libqt5widgets5t64",
        "libqt5network5t64",
        "libqt5test5t64",
        "libqt5dbus5t64",
        "libqt5concurrent5t64",
        "libqt5xml5t64",
        "libqt5sql5t64",
        "libqt5printsupport5t64",
        # Transitive shared-library dependencies of libQt5Core/libQt5Gui that
        # Ubuntu 26.04 does not ship in a default install.
        "libdouble-conversion3",
        "libpcre2-16-0",
        "libmd4c0",
        # What libQt5XcbQpa needs. Without these the xcb platform plugin fails
        # to load and no Qt application with a window can start at all.
        "libxcb-icccm4",
        "libxcb-image0",
        "libxcb-keysyms1",
        "libxcb-render-util0",
        "libxcb-util1",
        "libxcb-xinerama0",
        "libxcb-xinput0",
        "libxcb-xkb1",
        "libxkbcommon-x11-0",
    ],
    "opengl": [
        # GL/gl.h and friends.
        "mesa-common-dev",
        "libglvnd-core-dev",
        # The unversioned libGL.so/libGLX.so symlinks the linker resolves -lGL
        # against. Ubuntu ships the runtime .so.1 files but not these.
        "libgl-dev",
        "libglx-dev",
        "libopengl-dev",
        # The .so.N files the -dev symlinks resolve to.
        "libgl1",
        "libglx0",
        "libopengl0",
        "libglvnd0",
    ],
}


def resolve(package: str) -> tuple[str, str, str]:
    """Returns (version, url, sha256) for `package` at the host's apt version."""
    uris = subprocess.run(
        ["apt-get", "download", "--print-uris", package],
        capture_output=True, text=True, check=True).stdout.strip()
    if not uris:
        raise SystemExit(f"apt-get download --print-uris {package} returned nothing")
    url = uris.split(" ", 1)[0].strip("'")
    # apt points at whatever mirror is configured locally; pin the canonical
    # archive instead so the checked-in URLs work anywhere.
    url = re.sub(r"^https?://[^/]*archive\.ubuntu\.com/", "https://archive.ubuntu.com/", url)
    url = re.sub(r"^https?://[^/]*security\.ubuntu\.com/", "https://security.ubuntu.com/", url)
    show = subprocess.run(
        ["apt-cache", "show", package], capture_output=True, text=True, check=True).stdout
    fields = {}
    for line in show.splitlines():
        if line.startswith(("SHA256:", "Version:")) and ":" in line:
            key, value = line.split(":", 1)
            fields.setdefault(key, value.strip())
        if not line.strip():
            break  # Only look at the first (highest-priority) stanza.
    if "SHA256" not in fields:
        raise SystemExit(f"no SHA256 in apt-cache show {package}")
    return fields["Version"], url, fields["SHA256"]


def main() -> int:
    out = [
        "# Copyright (c) 2026 The Orbit Authors. All rights reserved.",
        "# Use of this source code is governed by a BSD-style license that can be",
        "# found in the LICENSE file.",
        "",
        '"""Pinned Ubuntu .deb artifacts. Generated by //bazel/deps:resolve_debs.py."""',
        "",
    ]
    for group, packages in GROUPS.items():
        out.append("%s_DEBS = [" % group.upper())
        for package in packages:
            version, url, sha256 = resolve(package)
            print(f"  {package} {version}", file=sys.stderr)
            out += [
                "    struct(",
                '        name = "%s",' % package,
                '        version = "%s",' % version,
                '        url = "%s",' % url,
                '        sha256 = "%s",' % sha256,
                "    ),",
            ]
        out += ["]", ""]

    target = Path(__file__).with_name("debs.bzl")
    target.write_text("\n".join(out))
    print(f"wrote {target}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
